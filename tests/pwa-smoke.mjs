import assert from 'node:assert/strict';
import fs from 'node:fs';
const read=p=>fs.readFileSync(p,'utf8');
const html=read('dist/BBQ_bereidingsplanner_MEATER_v4.html');
const entry=read('index.html');
const sw=read('sw.js');
const manifest=JSON.parse(read('manifest.webmanifest'));
assert.match(html,/viewport-fit=cover/);
assert.match(html,/apple-mobile-web-app-capable/);
assert.match(html,/id="v49-install"/);
assert.match(html,/id="v49-update"/);
assert.match(html,/function v49Init\(/);
assert.match(html,/v47Init\(\);v48Init\(\);v49Init\(\)/);
assert.equal((html.match(/data-v47-tab=/g)||[]).length,5);
assert.match(html,/meaterBridgeSeen/);
assert.match(html,/saveLocalRecipe/);
assert.match(entry,/manifest.webmanifest/);
assert.match(entry,/v=4.9.1/);
assert.equal(manifest.display,'standalone');
assert.ok(manifest.start_url.includes('BBQ_bereidingsplanner_MEATER_v4.html'));
assert.ok(manifest.icons.some(i=>i.src==='assets/apple-touch-icon.png'));
assert.ok(manifest.icons.some(i=>i.src==='assets/icon-512.png'&&i.sizes==='512x512'));
assert.match(sw,/assets\/icon-512\.png/);
assert.match(sw,/bbq-regisseur-v4\.9\.0/);
assert.match(sw,/SKIP_WAITING/);
assert.doesNotMatch(sw,/skipWaiting\(\)\s*\)\s*;\s*\}\)/);
assert.match(sw,/url\.origin!==self\.location\.origin/);
assert.match(sw,/SHELL\.includes\(canonical\)/);
assert.equal(sw.includes('https://api.'),false);
assert.ok(fs.existsSync('assets/apple-touch-icon.png'),'real PNG app icon');
assert.ok(fs.existsSync('assets/icon-512.png'),'512px PNG icon');
assert.equal(read('assets/app-icon.svg').includes('<svg'),true);
console.log('OK PWA v4.9.1 static checks');
